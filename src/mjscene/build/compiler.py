"""Scene spec -> MJCF (+ viewer sidecar + assets).

`compile_scene(spec, out_dir, spec_dir)` writes

    <out_dir>/scene.xml           full MJCF, self-contained
    <out_dir>/scene.viewer.json   rendering hints for the web viewer
    <out_dir>/scene.spec.json     the spec it was built from (provenance)
    <out_dir>/assets/*            generated heightfields, copied meshes/textures

Design notes
------------
* Everything that can be expressed as MJCF defaults goes into <default> so the
  generated XML stays readable and diffable.
* Assemblies are expanded to plain objects first (`spec.assemblies`), so prefabs
  and hand-written objects share one code path.
* Nothing external is required: materials use MuJoCo builtin procedural
  textures, terrain PNGs are generated by `build.terrain`.

This module is only the orchestrator + the shared compiler state. The actual
translation lives next door, as functions taking the `Compiler` as first
argument (no mixin magic — you can grep for where a section is built)::

    environment.py   option / visual / default / lights / ground
    geometry.py      assemblies + repeats + geoms + body tree
    assets.py        materials, textures, meshes, heightfields, robot models
    sidecar.py       scene.viewer.json
    mjcf.py          attribute formatting + camera math
"""

from __future__ import annotations

import copy
import json
import shutil
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

from .. import library
from . import assets, environment, geometry, procedural, sidecar, terrain
from .mjcf import look_at, set_attrs

__all__ = ["Compiler", "CompileResult", "compile_spec", "compile_scene"]


@dataclass
class CompileResult:
    """Everything one `compile_scene` produced."""

    xml: str
    viewer: dict
    assets: list[str] = field(default_factory=list)
    out_dir: Path | None = None
    object_index: list[dict] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


class Compiler:
    def __init__(self, spec: dict, spec_dir: Path):
        self.spec = copy.deepcopy(spec)
        self.spec_dir = Path(spec_dir)
        self.used_names: set[str] = set()
        self.materials: dict[str, dict] = {}    # name -> resolved material def
        self.textures: dict[str, dict] = {}     # texture element name -> attrs
        self.assets: list[str] = []             # relative paths under the scene dir
        self.model_assets: list[dict] = []      # <asset><model> child models (robots)
        self.copy_jobs: list[tuple[Path, str]] = []
        self.object_index: list[dict] = []
        self.notes: list[str] = []
        # Filled in by environment.build_ground, consumed by assets.build_assets
        # and compile_scene (which writes the PNG).
        self.hfield_asset: dict | None = None
        self.pending_terrain: dict | None = None
        # Procedural assets: (relative path, generator name, parameters); compile_scene writes them.
        self.pending_textures: list[tuple[str, str, dict]] = []
        self.pending_meshes: list[tuple[str, str, dict]] = []
        self.friction_profiles = dict(library.FRICTION)
        for fp in self.spec.get("friction_profiles") or []:
            self.friction_profiles[fp["name"]] = {
                "sliding": fp.get("sliding", 1.0),
                "torsional": fp.get("torsional", 0.005),
                "rolling": fp.get("rolling", 0.0001),
                "condim": fp.get("condim", 3),
            }
        self.defaults = {**{"condim": 3, "friction": "concrete", "contact": "default",
                            "margin": 0.0, "gap": 0.0, "density": 1000.0, "solmix": 1.0},
                         **(self.spec.get("defaults") or {})}

    # -- names ------------------------------------------------------------
    def uniq(self, base: str) -> str:
        """Reserve a unique MJCF name, suffixing on collision.

        A silent rename would break `contacts.pairs` references (and confuse any
        script looking the body up), so every collision lands in `notes`.
        """
        name = base
        i = 1
        while name in self.used_names:
            i += 1
            name = f"{base}_{i}"
        if name != base:
            self.notes.append(
                f"Name '{base}' is already used (possibly by an assembly child); "
                f"renamed this object to '{name}'. References should use '{name}_geom'")
        self.used_names.add(name)
        return name

    # -- friction / contact ----------------------------------------------
    def friction(self, ref):
        if ref is None:
            return None
        if isinstance(ref, (list, tuple)):
            vals = [float(v) for v in ref]
            return (vals + [0.005, 0.0001])[:3]
        p = self.friction_profiles[ref]
        return [p["sliding"], p["torsional"], p["rolling"]]

    def friction_condim(self, ref) -> int | None:
        if isinstance(ref, str):
            return self.friction_profiles.get(ref, {}).get("condim")
        return None

    @staticmethod
    def contact_profile(ref):
        return library.CONTACT_PROFILES[ref] if ref else None

    # -- assets (thin delegates, used from every build_* module) -----------
    def material(self, name: str | None) -> str | None:
        """Register a material (preset or user-defined) and return its MJCF name."""
        return assets.material(self, name)

    def stage_asset(self, rel_path: str) -> str:
        """Schedule an external file for copying into <out>/assets."""
        return assets.stage_asset(self, rel_path)

    # ------------------------------------------------------------------ #
    # top level
    # ------------------------------------------------------------------ #
    def build(self) -> CompileResult:
        """Assemble the whole MJCF document, section by section."""
        spec = self.spec
        root = ET.Element("mujoco", {"model": spec.get("name", "scene")})
        root.append(ET.Comment(
            " Generated by mjscene from the scene spec - edit the .scene.json, not this file. "))

        set_attrs(ET.SubElement(root, "compiler"), angle="degree", autolimits=True,
                  assetdir="assets", eulerseq="xyz")

        environment.build_option(self, root)
        asset_el = ET.SubElement(root, "asset")      # filled in last (needs materials)
        environment.build_visual(self, root)
        environment.build_default(self, root)

        world = ET.SubElement(root, "worldbody")
        environment.build_lights(self, world)
        environment.build_ground(self, world, asset_el)

        for obj in geometry.expand_objects(self):
            geometry.build_object(self, world, obj, parent_static=False)

        assets.build_robots(self, root, world)
        self.build_cameras(world)
        self.build_spawn(world)
        self.build_contacts(root)
        assets.build_assets(self, asset_el)

        if spec.get("raw_mjcf"):
            self.append_raw(root, spec["raw_mjcf"])

        ET.indent(root, space="  ")
        xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
               + ET.tostring(root, encoding="unicode") + "\n")
        return CompileResult(xml=xml, viewer=self.build_viewer(), assets=list(self.assets),
                             object_index=self.object_index, notes=self.notes)

    # -- cameras / contacts / raw ------------------------------------------
    def build_cameras(self, world):
        cams = self.spec.get("cameras") or []
        if not cams:
            return
        world.append(ET.Comment(" cameras "))
        for c in cams:
            el = ET.SubElement(world, "camera")
            attrs = {"name": self.uniq(c["name"]), "pos": c["pos"], "fovy": c.get("fovy", 50)}
            if c.get("target") is not None:
                attrs["xyaxes"] = look_at(c["pos"], c["target"])
            elif c.get("euler") is not None:
                attrs["euler"] = c["euler"]
            mode = c.get("mode", "fixed")
            if mode != "fixed":
                attrs["mode"] = mode
                if c.get("track"):
                    attrs["target"] = c["track"]
            set_attrs(el, **attrs)

    def build_spawn(self, world):
        """Emit the spawn point as a site.

        The site has no collision or dynamic effect, but records the compiled
        geometric location. When a downstream host uses `<attach>`, MuJoCo moves
        the site and prefixes its name. The host can then query its world
        coordinates instead of manually transforming manifest values.
        """
        spawn = self.spec.get("spawn")
        if not spawn:
            return
        world.append(ET.Comment(" robot spawn "))
        el = ET.SubElement(world, "site")
        set_attrs(el, name=self.uniq("spawn"), pos=spawn.get("position", [0.0, 0.0, 0.0]),
                  euler=[0.0, 0.0, spawn.get("yaw", 0.0)], type="sphere", size=[0.02],
                  group=4, rgba=[0.2, 0.9, 0.4, 0.5])

    def build_contacts(self, root):
        c = self.spec.get("contacts") or {}
        pairs = c.get("pairs") or []
        excludes = c.get("excludes") or []
        if not pairs and not excludes:
            return
        el = ET.SubElement(root, "contact")
        for p in pairs:
            pe = ET.SubElement(el, "pair")
            fric = p.get("friction")
            if isinstance(fric, str):
                t = self.friction(fric)
                fric = [t[0], t[0], t[1], t[2], t[2]]      # pair needs 5 numbers
            set_attrs(pe, geom1=p["geom1"], geom2=p["geom2"], friction=fric,
                      solref=p.get("solref"), solimp=p.get("solimp"),
                      condim=p.get("condim"), margin=p.get("margin"), gap=p.get("gap"))
        for x in excludes:
            set_attrs(ET.SubElement(el, "exclude"), body1=x["body1"], body2=x["body2"])

    def append_raw(self, root, raw: str):
        """Splice the `raw_mjcf` escape hatch into the document."""
        try:
            wrapper = ET.fromstring(f"<wrap>{raw}</wrap>")
        except ET.ParseError as exc:
            raise ValueError(f"raw_mjcf is not valid XML: {exc}") from exc
        for child in list(wrapper):
            root.append(child)

    # -- viewer sidecar ----------------------------------------------------
    def build_viewer(self) -> dict:
        """Rendering hints for the web viewer (see build/sidecar.py)."""
        return sidecar.build_viewer(self)


# --------------------------------------------------------------------------- #
# public API
# --------------------------------------------------------------------------- #


def compile_spec(spec: dict, spec_dir: Path | str = ".") -> CompileResult:
    """Compile a spec in memory (no files written)."""
    return Compiler(spec, Path(spec_dir)).build()


def compile_scene(spec: dict, out_dir: Path | str, spec_dir: Path | str = ".") -> CompileResult:
    """Compile and write scene.xml + sidecars + assets into `out_dir`."""
    c = Compiler(spec, Path(spec_dir))
    result = c.build()
    out = Path(out_dir)
    (out / "assets").mkdir(parents=True, exist_ok=True)
    (out / "scene.xml").write_text(result.xml, encoding="utf-8")
    (out / "scene.viewer.json").write_text(
        json.dumps(result.viewer, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "scene.spec.json").write_text(
        json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    written: set[Path] = set()
    for src, dest_rel in c.copy_jobs:
        shutil.copy2(src, out / dest_rel)
        written.add(out / dest_rel)
    for rel, gen, params in c.pending_textures:
        procedural.generate_texture(gen, out / rel, params)
        written.add(out / rel)
    for rel, gen, params in c.pending_meshes:
        procedural.generate_mesh(gen, out / rel, params)
        written.add(out / rel)
    pending = c.pending_terrain
    if pending:
        rel = pending.pop("rel")
        terrain.write_heightfield(out / rel, pending.pop("kind"), pending.pop("res"), **pending)
        written.add(out / rel)

    # Remove stale generated files. build/ is compiled output, not an archive.
    # Otherwise assets removed or renamed in the spec could remain in exports.
    stale = sorted(f for f in (out / "assets").rglob("*") if f.is_file() and f not in written)
    for f in stale:
        f.unlink()
    if stale:
        result.notes.append(
            f"Removed {len(stale)} stale assets from the previous build: "
            + ", ".join(f.name for f in stale[:4]) + (" …" if len(stale) > 4 else ""))
    if (out / "assets").exists() and not any((out / "assets").iterdir()):
        (out / "assets").rmdir()
    result.out_dir = out
    return result
